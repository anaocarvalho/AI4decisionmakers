import type { Config } from "@jobscout/core";

export const STATUSES = ["new", "interested", "materials_drafted", "applied", "interview", "offer", "rejected"] as const;
export type Status = (typeof STATUSES)[number];
const LABEL: Record<Status, string> = {
  new: "New", interested: "Interested", materials_drafted: "Materials drafted", applied: "Applied", interview: "Interview", offer: "Offer", rejected: "Rejected",
};

export interface DigestJob {
  title: string;
  company: string;
  location: string;
  is_remote: boolean;
  url: string;
  rank_score: number | null;
  sponsorship_status: string;
  fit_rationale: string | null;
}

export interface DigestInput {
  weekEnding: Date;
  newJobsCount: number;
  topJobs: DigestJob[];
  statusCounts: Record<Status, number>;
  appliedThisWeek: number;
  siteUrl?: string;
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

export function digestTitle(d: DigestInput): string {
  return `JobScout weekly digest: week ending ${d.weekEnding.toISOString().slice(0, 10)}`;
}

export function buildDigest(d: DigestInput, cfg: Config): string {
  const lines: string[] = [];
  lines.push(`**${d.newJobsCount}** new jobs this week · **${d.topJobs.length}** scored ${cfg.scoring.highlight_threshold}+ · **${d.appliedThisWeek}** applications this week`);
  if (d.siteUrl) lines.push("", `Open the tracker: ${d.siteUrl}`);
  lines.push("", "### Pipeline", "", "| " + STATUSES.map((s) => LABEL[s]).join(" | ") + " |", "|" + STATUSES.map(() => "---:").join("|") + "|");
  lines.push("| " + STATUSES.map((s) => String(d.statusCounts[s] ?? 0)).join(" | ") + " |");
  lines.push("", `### New high-fit jobs (score ≥ ${cfg.scoring.highlight_threshold})`, "");
  if (!d.topJobs.length) {
    lines.push("_None this week._");
  } else {
    lines.push("| Score | Job | Location | Sponsorship | Why |", "|---:|---|---|---|---|");
    for (const j of d.topJobs) {
      const flag = j.sponsorship_status === "blocked" ? "⚠️ no sponsorship" : j.sponsorship_status === "friendly" ? "✅ OPT-friendly" : "—";
      const where = j.location || (j.is_remote ? "Remote" : "");
      lines.push(`| ${j.rank_score ?? "–"} | [${cell(j.title)}](${j.url}), ${cell(j.company)} | ${cell(where)}${j.is_remote && !/remote/i.test(where) ? " (remote)" : ""} | ${flag} | ${cell(j.fit_rationale ?? "")} |`);
    }
  }
  lines.push("", "<sub>Generated by the JobScout weekly-digest workflow. JobScout never applies on your behalf.</sub>");
  return lines.join("\n");
}
